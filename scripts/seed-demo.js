// Seeds a clearly labelled synthetic demo workspace for YC/Speedrun walkthroughs, and writes synthetic sample files.
//
//   node --env-file-if-exists=.env scripts/seed-demo.js [--files-dir .local/demo-files]
//
// Creates (or reuses) two accounts with confirmed emails and freshly generated passwords, shown once:
//   - the demo owner of "Northwind Packaging (synthetic demo)"
//   - a demo staff reviewer with no membership in that workspace (add its email to DEMO_STAFF_EMAILS with
//     DEMO_WORKSPACE_ID set to the workspace id printed below; never to the global STAFF_EMAILS)
// Nothing here is real customer data. Refuses to run with NODE_ENV=production unless --allow-production is given.
import { mkdirSync, writeFileSync } from 'node:fs';
import { randomBytes } from 'node:crypto';
import { deflateSync } from 'node:zlib';
import { join, resolve } from 'node:path';
import { hashPassword } from '../src/lib/passwords.js';
import { createStore } from '../src/store/index.js';
import { loadConfig } from '../src/config.js';

const OWNER = { email: 'demo.owner@northwind-demo.example', name: 'Demo Owner (synthetic)' };
const STAFF = { email: 'demo.reviewer@valcairn.example', name: 'Valcairn Reviewer (demo)' };
const WORKSPACE = { name: 'Northwind Packaging (synthetic demo)', slug: 'northwind-demo' };

const args = process.argv.slice(2);
const filesDir = resolve(args[args.indexOf('--files-dir') + 1] && args.includes('--files-dir') ? args[args.indexOf('--files-dir') + 1] : '.local/demo-files');
if (process.env.NODE_ENV === 'production' && !args.includes('--allow-production')) {
  console.error('Refusing to seed demo data with NODE_ENV=production. Pass --allow-production to a demo-only database if you mean it.');
  process.exit(2);
}

// Minimal PNG encoder for synthetic images: a box on a conveyor, intact or with a damaged corner.
function crc32(buf) {
  let c, crc = 0xffffffff;
  for (const b of buf) {
    c = (crc ^ b) & 0xff;
    for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
    crc = (crc >>> 8) ^ c;
  }
  return (crc ^ 0xffffffff) >>> 0;
}
function chunk(type, data) {
  const len = Buffer.alloc(4); len.writeUInt32BE(data.length);
  const td = Buffer.concat([Buffer.from(type), data]);
  const crc = Buffer.alloc(4); crc.writeUInt32BE(crc32(td));
  return Buffer.concat([len, td, crc]);
}
function boxImage(seed, damaged) {
  const w = 96, h = 72;
  const rows = [];
  for (let y = 0; y < h; y++) {
    const row = [0];
    for (let x = 0; x < w; x++) {
      const inBox = x > 20 + (seed % 7) && x < 76 - (seed % 5) && y > 14 && y < 60;
      const dent = damaged && inBox && x + y < 54 + (seed % 9);
      const [r, g, b] = dent ? [120, 72, 40] : inBox ? [196, 150, 98] : y > 60 ? [70, 70, 76] : [228, 230, 234];
      row.push(r, g, b);
    }
    rows.push(Buffer.from(row));
  }
  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(w, 0); ihdr.writeUInt32BE(h, 4); ihdr[8] = 8; ihdr[9] = 2;
  return Buffer.concat([Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]), chunk('IHDR', ihdr), chunk('IDAT', deflateSync(Buffer.concat(rows))), chunk('IEND', Buffer.alloc(0))]);
}

function writeFiles() {
  mkdirSync(filesDir, { recursive: true });
  const labels = ['filename,label'];
  for (let i = 1; i <= 6; i++) {
    const damaged = i % 3 === 0;
    const name = `line2-box-${String(i).padStart(3, '0')}.png`;
    writeFileSync(join(filesDir, name), boxImage(i, damaged));
    labels.push(`${name},${damaged ? 'damaged' : 'ok'}`);
  }
  // An exact copy under another name, to show duplicate detection.
  writeFileSync(join(filesDir, 'line2-box-001-copy.png'), boxImage(1, false));
  writeFileSync(join(filesDir, 'labels.csv'), `${labels.join('\n')}\n`);
  writeFileSync(join(filesDir, 'README.txt'), 'Synthetic demo files generated by scripts/seed-demo.js. Not real customer data.\n');
}

async function ensureUser(store, { email, name }) {
  const password = randomBytes(12).toString('base64url');
  const existing = await store.getUserAuthByEmail(email);
  if (existing) return { user: existing.user, password: null };
  const user = await store.createUser({ email, name, passwordHash: await hashPassword(password) });
  await store.setEmailVerified(user.id);
  return { user, password };
}

const config = loadConfig({ ...process.env, NODE_ENV: process.env.NODE_ENV === 'production' ? 'production' : 'development' });
if (!config.databaseUrl) {
  console.error('Set DATABASE_URL: demo data is only useful in a persistent database.');
  process.exit(2);
}
const store = await createStore(config);
try {
  const owner = await ensureUser(store, OWNER);
  const staff = await ensureUser(store, STAFF);
  const mine = await store.listWorkspacesForUser(owner.user.id);
  let workspace = mine.find((m) => m.workspace.slug === WORKSPACE.slug)?.workspace;
  if (!workspace) {
    workspace = await store.createWorkspace({
      kind: 'organization', ...WORKSPACE, website: null, domain: null, industry: 'Manufacturing and industrial', sizeBand: '51–200',
      profile: { synthetic: true, note: 'Synthetic demo workspace. Not a real customer.' }, ownerId: owner.user.id,
    });
  }
  writeFiles();
  console.log(`Workspace: ${workspace.name}  →  /w/${workspace.slug}`);
  console.log(`Workspace id: ${workspace.id}  (set DEMO_WORKSPACE_ID to this to show it on /demo/review)`);
  console.log(`Owner:     ${OWNER.email}  ${owner.password ? `password: ${owner.password}` : '(already existed; password unchanged)'}`);
  console.log(`Staff:     ${STAFF.email}  ${staff.password ? `password: ${staff.password}` : '(already existed; password unchanged)'}`);
  console.log(`Files:     ${filesDir}`);
  if (!config.demoStaffEmails.includes(STAFF.email) || config.demoWorkspaceId !== workspace.id) console.log(`Set DEMO_WORKSPACE_ID=${workspace.id} and add ${STAFF.email} to DEMO_STAFF_EMAILS so it can review this workspace only (never STAFF_EMAILS).`);
  console.log('Passwords are shown only now. Keep them outside Git.');
} finally {
  await store.close();
}
